"""Regenerate ``src/aninest/_tag_tables.py`` from the assistant's own table.

The tag dictionary in this project is not invented here: it is the one the
author's personal assistant already uses, so that the MCP server and the
assistant answer the same query with the same tags. Keeping a copy in the repo
makes the server installable without that assistant, and this script makes the
copy reproducible instead of a hand-maintained fork.

The assistant's module is not shipped (it is not part of this repository), so
point the script at your own checkout::

    python scripts/port_tags.py --source path/to/astrbot_plugin_art_gallery/tagging.py

Without ``--source`` it tries ``ANINEST_TAG_SOURCE`` and then a few default
locations from the author's machine. If none of them exists the script stops
with a clear message rather than writing a half-empty table.
"""

from __future__ import annotations

import argparse
import importlib.util
import os
import sys
from pathlib import Path

CORE_TABLES = ("CN_TAG_ALIASES", "CN_CHARACTERS", "STOP_PHRASES", "BLOCKED_TAGS", "BLOCKED_CN")
#: Anything else in the source module that is a plain data table (``_CN_NUM``,
#: ``_ORIENTATION_WORDS`` …) is carried over too — the parser needs all of them,
#: and silently dropping one only shows up as a crash at import time.
DATA_TYPES = (dict, tuple, list, frozenset, set)

DEFAULT_SOURCES = (
    r"<assistant-plugins-dir>"
    r"\astrbot_plugin_art_gallery\tagging.py",
)

HEADER = '''"""Chinese -> booru tag dictionary, ported from the assistant's table.

Generated by ``scripts/port_tags.py`` - do not edit by hand. The values are the
same ones the assistant uses, so a query means the same thing on both sides.
"""

from __future__ import annotations

'''

FOOTER = '''
def counts() -> dict[str, int]:
    """Quick sanity numbers used by tests and the docs."""
    return {name: len(globals()[name]) for name in _TABLE_NAMES}
'''


def load_source(path: Path):
    spec = importlib.util.spec_from_file_location("_aninest_tag_source", path)
    if spec is None or spec.loader is None:
        raise SystemExit(f"cannot import {path}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def find_source(explicit: str | None) -> Path:
    for candidate in (explicit, os.environ.get("ANINEST_TAG_SOURCE"), *DEFAULT_SOURCES):
        if candidate and Path(candidate).is_file():
            return Path(candidate)
    raise SystemExit(
        "找不到助手的词典文件：用 --source 指向 astrbot_plugin_art_gallery/tagging.py，"
        "或设置 ANINEST_TAG_SOURCE。"
    )


def table_names(module) -> list[str]:
    """Core tables first (stable order), then any other data-only globals."""
    names = list(CORE_TABLES)
    for name, value in vars(module).items():
        if name in names or name.startswith("__"):
            continue
        if (name.startswith("_") or name.isupper()) and isinstance(value, DATA_TYPES):
            names.append(name)
    return names


def render(module) -> tuple[str, list[str]]:
    names = table_names(module)
    parts = [HEADER]
    parts.append("_TABLE_NAMES: tuple = " + repr(tuple(names)) + "\n\n")
    for name in names:
        parts.append(f"{name}: dict = {getattr(module, name)!r}\n\n")
    parts.append(FOOTER)
    return "".join(parts), names


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--source", help="path to the assistant's tagging.py")
    parser.add_argument(
        "--out",
        default=str(Path(__file__).resolve().parents[1] / "src" / "aninest" / "_tag_tables.py"),
        help="where to write the tables (default: src/aninest/_tag_tables.py)",
    )
    args = parser.parse_args(argv)

    source = find_source(args.source)
    module = load_source(source)
    text, names = render(module)
    out = Path(args.out)
    out.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {out} from {source}")
    print("  " + "  ".join(f"{n}={len(getattr(module, n))}" for n in names))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
